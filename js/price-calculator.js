const updatePricesInCards = () => {
    const gramInput = document.getElementById('gram');
    const grams = isNaN(parseFloat(gramInput.value)) ? 1 : parseFloat(gramInput.value);

    if (!priceData) return;

    const buyPriceElements = document.querySelectorAll('.buy-price');
    const sellPriceElements = document.querySelectorAll('.sell-price');

    buyPriceElements.forEach(element => {
        const basePrice = parseFloat(element.getAttribute('data-base'));
        const calculatedPrice = (basePrice * grams).toFixed(3);
        element.textContent = calculatedPrice;
    });

    sellPriceElements.forEach(element => {
        const basePrice = parseFloat(element.getAttribute('data-base'));
        const calculatedPrice = (basePrice * grams).toFixed(3);
        element.textContent = calculatedPrice;
    });
};

